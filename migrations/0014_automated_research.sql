CREATE TABLE IF NOT EXISTS automated_research_days (
  event_date TEXT PRIMARY KEY,
  status TEXT NOT NULL CHECK (status IN ('pending','running','retry','done','needs_review')),
  attempts INTEGER NOT NULL DEFAULT 0,
  last_started_at TEXT,
  lease_expires_at TEXT,
  completed_at TEXT,
  last_error TEXT,
  outcome TEXT CHECK (outcome IN ('updated','no-findings') OR outcome IS NULL),
  findings_count INTEGER NOT NULL DEFAULT 0,
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_automated_research_days_status
  ON automated_research_days(status, attempts, event_date);

CREATE TABLE IF NOT EXISTS automated_research_runs (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  kind TEXT NOT NULL CHECK (kind IN ('backfill','daily')),
  target_date TEXT NOT NULL,
  started_at TEXT NOT NULL,
  finished_at TEXT,
  status TEXT NOT NULL CHECK (status IN ('running','success','error')),
  discovered_count INTEGER NOT NULL DEFAULT 0,
  finding_count INTEGER NOT NULL DEFAULT 0,
  attack_write_count INTEGER NOT NULL DEFAULT 0,
  incident_write_count INTEGER NOT NULL DEFAULT 0,
  ambiguous_count INTEGER NOT NULL DEFAULT 0,
  error_message TEXT
);

CREATE INDEX IF NOT EXISTS idx_automated_research_runs_kind_started
  ON automated_research_runs(kind, started_at DESC);

