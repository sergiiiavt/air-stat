// Builds migrations/0024_import_kyiv_oblast_alert_history.sql from the
// "official" file of the ukrainian-air-raid-sirens-dataset (MIT,
// https://github.com/Vadimkin/ukrainian-air-raid-sirens-dataset), which records
// the national air-alert channel's oblast/raion/hromada alerts with explicit
// start and end times in UTC from 2022-03-15.
//
// Usage: node scripts/build-kyiv-oblast-alert-history.mjs <official_data_uk.csv> <dataset-commit-sha>
//
// Only Kyiv Oblast rows that start before the KOVA history window
// (KOVA_COVERAGE_START) are emitted, so existing collector intervals are not
// changed. Exact duplicate rows in the dataset are removed. Inserts are
// idempotent (INSERT OR IGNORE on the (scope, external_id) unique index).
import { readFileSync, writeFileSync } from 'node:fs';

export const KOVA_COVERAGE_START = '2026-05-16T20:18:31.004Z';
export const DATASET_REPO = 'https://github.com/Vadimkin/ukrainian-air-raid-sirens-dataset';
export const SOURCE_KEY = 'air_raid_sirens_dataset';

export function parseCsv(text) {
  const rows = [];
  let field = '';
  let row = [];
  let quoted = false;
  for (let index = 0; index < text.length; index += 1) {
    const char = text[index];
    if (quoted) {
      if (char === '"' && text[index + 1] === '"') {
        field += '"';
        index += 1;
      } else if (char === '"') {
        quoted = false;
      } else {
        field += char;
      }
    } else if (char === '"') {
      quoted = true;
    } else if (char === ',') {
      row.push(field);
      field = '';
    } else if (char === '\n' || char === '\r') {
      if (char === '\r' && text[index + 1] === '\n') index += 1;
      row.push(field);
      rows.push(row);
      row = [];
      field = '';
    } else {
      field += char;
    }
  }
  if (field || row.length) {
    row.push(field);
    rows.push(row);
  }
  const [header, ...body] = rows.filter((value) => value.length > 1 || value[0]);
  return body.map((values) => Object.fromEntries(header.map((name, index) => [name, values[index] ?? ''])));
}

export function kyivDate(iso) {
  const parts = new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Europe/Kyiv',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).formatToParts(new Date(iso));
  const values = Object.fromEntries(parts.map((part) => [part.type, part.value]));
  return `${values.year}-${values.month}-${values.day}`;
}

function toIso(value) {
  const date = new Date(value.replace(' ', 'T'));
  if (Number.isNaN(date.getTime())) throw new Error(`Invalid dataset timestamp: ${value}`);
  return date.toISOString();
}

export function kyivOblastIntervals(rows) {
  const unique = new Map();
  for (const row of rows) {
    if (!row.oblast.startsWith('Київська обл')) continue;
    if (!['oblast', 'raion', 'hromada'].includes(row.level)) continue;
    const startedAt = toIso(row.started_at);
    const endedAt = toIso(row.finished_at);
    if (startedAt >= KOVA_COVERAGE_START) continue;
    if (endedAt <= startedAt) continue;
    const adminArea = row.level === 'oblast'
      ? 'Kyiv Oblast'
      : row.level === 'raion'
        ? row.raion
        : row.hromada;
    if (!adminArea) continue;
    const externalId = `sirens:${row.level}:${adminArea}:${startedAt}`;
    if (!unique.has(externalId)) {
      unique.set(externalId, { externalId, startedAt, endedAt, localDate: kyivDate(startedAt), adminArea });
    }
  }
  return [...unique.values()].sort((a, b) => a.startedAt.localeCompare(b.startedAt));
}

const sql = (value) => `'${String(value).replaceAll("'", "''")}'`;

export function buildMigration(intervals, commitSha) {
  const sourceUrl = `${DATASET_REPO}/blob/${commitSha}/datasets/official_data_uk.csv`;
  const header = [
    '-- Kyiv Oblast historical alert intervals, 2022-03-15 .. KOVA coverage start.',
    `-- Generated by scripts/build-kyiv-oblast-alert-history.mjs from ${DATASET_REPO}`,
    `-- (MIT) at commit ${commitSha}, file datasets/official_data_uk.csv: the national`,
    '-- air-alert channel\'s oblast, raion and hromada alerts with explicit UTC start/end.',
    `-- Cross-checked against KOVA intervals for June 2026 (daily counts and seconds agree).`,
    `-- ${intervals.length} unique intervals; rows starting at or after ${KOVA_COVERAGE_START}`,
    '-- are excluded so collector data is unchanged. Durations are unioned per scope by',
    '-- the existing aggregation; no level is inferred (alert_level = unknown).',
  ].join('\n');
  const chunks = [];
  for (let index = 0; index < intervals.length; index += 100) {
    const values = intervals.slice(index, index + 100).map((item) =>
      `(${sql(item.externalId)}, 'kyiv-oblast', ${sql(item.startedAt)}, ${sql(item.endedAt)}, ` +
      `${sql(item.localDate)}, 'air_raid', '[]', ${sql(SOURCE_KEY)}, ${sql(sourceUrl)}, ` +
      `${sql(item.adminArea)}, 'unknown')`);
    chunks.push(
      'INSERT OR IGNORE INTO alert_events (external_id, scope, started_at, ended_at, local_date, ' +
        'alert_type, threat_types_json, source_key, source_url, admin_area, alert_level) VALUES\n' +
        values.join(',\n') + ';',
    );
  }
  return `${header}\n\n${chunks.join('\n\n')}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const [csvPath, commitSha] = process.argv.slice(2);
  if (!csvPath || !/^[0-9a-f]{40}$/.test(commitSha ?? '')) {
    throw new Error('Usage: build-kyiv-oblast-alert-history.mjs <official_data_uk.csv> <40-char commit sha>');
  }
  const intervals = kyivOblastIntervals(parseCsv(readFileSync(csvPath, 'utf8')));
  writeFileSync(
    new URL('../migrations/0024_import_kyiv_oblast_alert_history.sql', import.meta.url),
    buildMigration(intervals, commitSha),
  );
  console.log(`Wrote ${intervals.length} Kyiv Oblast intervals (${intervals[0]?.startedAt} .. ${intervals.at(-1)?.startedAt}).`);
}
