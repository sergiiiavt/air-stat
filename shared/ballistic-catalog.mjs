export function mergeBallisticEvidence(research, verified, from, to) {
  const entries = verified.filter((x) => x.date >= from && x.date <= to);
  const verifiedDays = new Set(entries.map((x) => x.date));
  // The current automated research stores one attack per day/scope; its entries
  // on manually reviewed dates refer to the same campaign and must not double count.
  const recovered = research.filter((x) => !verifiedDays.has(x.date));
  return [...entries, ...recovered].sort((a,b) =>
    b.date.localeCompare(a.date) || String(a.id).localeCompare(String(b.id))
  );
}

export function explicitlyBallisticResearch(summary, threatTypes) {
  if (Array.isArray(threatTypes) && threatTypes.includes('ballistic')) return true;
  if (typeof summary !== 'string') return false;
  const normalized = summary.toLowerCase();
  const mentionsWeapon = /ballistic|балістич|іскандер|iskander/.test(normalized);
  const describesAttack = /attack|strike|hit|launched|fired|missile.{0,30}struck|удар|атак|влуч|обстріл/.test(normalized);
  const onlyWarning = /^(?:.*(?:warning|alert|threat|загроз|тривог))/.test(normalized) && !describesAttack;
  return mentionsWeapon && describesAttack && !onlyWarning;
}
